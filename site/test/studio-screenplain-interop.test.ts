import { readFileSync } from "node:fs";
import { type Browser, type Page, chromium } from "playwright";
import { ModuleKind, ScriptTarget, transpileModule } from "typescript";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { exportFdx } from "../src/studio/fdx";
import type { importFdx } from "../src/studio/fdx-import";
import { parseFountain } from "../src/studio/fountain";
import { fountainRuns } from "../src/studio/inline";

const fixture = (name: string) =>
  readFileSync(new URL(`./fixtures/studio-interop/${name}`, import.meta.url), "utf8");
const source = fixture("lantern.fountain");
// Generated by an actual pinned Screenplain process, not by Studio or hand-written XML.
const independentXml = fixture("lantern.screenplain.fdx");
const modules = new Map<string, string>();
function compile(name: string): string {
  const cached = modules.get(name);
  if (cached) return cached;
  const js = transpileModule(
    readFileSync(new URL(`../src/studio/${name}.ts`, import.meta.url), "utf8"),
    { compilerOptions: { target: ScriptTarget.ES2022, module: ModuleKind.ES2022 } },
  ).outputText.replace(/"\.\/([a-z-]+)"/g, (_, dep: string) => JSON.stringify(compile(dep)));
  const result = `data:text/javascript;base64,${Buffer.from(js).toString("base64")}`;
  modules.set(name, result);
  return result;
}
let browser: Browser;
let page: Page;
beforeAll(async () => {
  browser = await chromium.launch();
  page = await browser.newPage();
  await page.addScriptTag({
    type: "module",
    content: `import {importFdx} from ${JSON.stringify(compile("fdx-import"))};window.importFdx=importFdx;`,
  });
  await page.waitForFunction(
    () => !!(window as unknown as { importFdx: typeof importFdx }).importFdx,
  );
});
afterAll(async () => browser.close());
const convert = (xml: string) =>
  page.evaluate(
    (xml) =>
      (window as unknown as { importFdx: typeof importFdx }).importFdx(
        new TextEncoder().encode(xml),
      ),
    xml,
  );
const excluded = new Set(["blank", "title", "note", "boneyard", "section", "synopsis"]);
function visible(value: string, numbers = true) {
  return parseFountain(value)
    .elements.filter((e) => !excluded.has(e.kind))
    .map((e) => ({
      kind: e.kind,
      glyphs: fountainRuns(e.text).flatMap((run) =>
        Array.from(run.text, (text) => ({ ...run, text })),
      ),
      number: numbers ? (e.sceneNumber ?? null) : null,
      dual: !!e.dual,
    }));
}

/** Independent XML oracle: inspect only standard DOM nodes, never the Studio
 * importer or Fountain parser. Normalize producers' paragraph/line grouping and
 * Text-run boundaries while retaining every visible character and style flag. */
async function xmlFacts(xml: string) {
  return page.evaluate((xml) => {
    const doc = new DOMParser().parseFromString(xml, "application/xml");
    if (doc.querySelector("parsererror")) throw new Error("Malformed exported XML");
    const content = doc.documentElement.querySelector(":scope > Content");
    if (!content) throw new Error("Missing body");
    const types: Record<string, string> = {
      "Scene Heading": "scene",
      Action: "action",
      Character: "character",
      Parenthetical: "parenthetical",
      Dialogue: "dialogue",
      Transition: "transition",
    };
    const lines: {
      kind: string;
      glyphs: { text: string; bold: boolean; italic: boolean; underline: boolean }[];
      number: string | null;
      dual: boolean;
    }[] = [];
    let lastDual: Element | null = null;
    let dualCharacters = 0;
    for (const paragraph of content.querySelectorAll("Paragraph[Type]")) {
      const type = paragraph.getAttribute("Type") as string;
      if (!types[type]) throw new Error(`Unexpected exported type ${type}`);
      const dual =
        paragraph.parentElement?.tagName === "DualDialogue" ? paragraph.parentElement : null;
      if (dual !== lastDual) dualCharacters = 0;
      lastDual = dual;
      if (dual && type === "Character") dualCharacters++;
      const makeLine = () => ({
        kind:
          type === "Action" && paragraph.getAttribute("Alignment") === "Center"
            ? "centered"
            : (types[type] as string),
        glyphs: [] as { text: string; bold: boolean; italic: boolean; underline: boolean }[],
        number: paragraph.getAttribute("Number"),
        dual: !!dual && type === "Character" && dualCharacters === 2,
      });
      let line = makeLine();
      for (const node of paragraph.children) {
        if (node.tagName !== "Text") throw new Error("Unexpected public paragraph child");
        const styles = new Set((node.getAttribute("Style") ?? "").split("+"));
        for (const text of node.textContent ?? "") {
          if (text === "\n") {
            if (line.glyphs.length) lines.push(line);
            line = makeLine();
          } else
            line.glyphs.push({
              text,
              bold: styles.has("Bold"),
              italic: styles.has("Italic"),
              underline: styles.has("Underline"),
            });
        }
      }
      if (line.glyphs.length) lines.push(line);
    }
    return {
      root: doc.documentElement.tagName,
      documentType: doc.documentElement.getAttribute("DocumentType"),
      dualPairs: content.querySelectorAll("DualDialogue").length,
      titlePages: doc.querySelectorAll("TitlePage").length,
      lines,
    };
  }, xml);
}

describe("pinned Screenplain 0.12.0 interchange", () => {
  it("records the actual producer omissions without mistaking them for importer loss", async () => {
    const facts = await xmlFacts(independentXml);
    expect(facts.root).toBe("FinalDraft");
    expect(facts.documentType).toBe("Script");
    expect(facts.dualPairs).toBe(1);
    expect(facts.titlePages).toBe(0);
    expect(facts.lines.every((line) => line.number === null)).toBe(true);
    expect(facts.lines).toEqual(visible(source, false));
    expect(independentXml).not.toMatch(/PRIVATE_|fixture-contact|Lantern Test/);
  });
  it("imports independently generated roles, exact Unicode text, styles and dual dialogue", async () => {
    const result = await convert(independentXml);
    expect(result.dualPairs).toBe(1);
    expect(visible(result.source)).toEqual((await xmlFacts(independentXml)).lines);
    expect(result.source).not.toMatch(/PRIVATE_|fixture-contact|Lantern Test/);
    expect(parseFountain(result.source).warnings).toEqual([]);
    expect(parseFountain(result.source).omissions).toEqual([]);
  });
  it("exports source to independent XML expectations, including numbers Screenplain omits", async () => {
    const ours = exportFdx(source, { includeTitle: false });
    const facts = await xmlFacts(ours.xml);
    expect(facts.lines).toEqual(visible(source));
    expect(facts.lines.map((line) => ({ ...line, number: null }))).toEqual(
      (await xmlFacts(independentXml)).lines,
    );
    expect(facts.lines.filter((line) => line.kind === "scene").map((line) => line.number)).toEqual([
      "12A",
      "13",
    ]);
    expect(facts.dualPairs).toBe(1);
    expect(facts.titlePages).toBe(0);
    expect(ours.xml).not.toMatch(/PRIVATE_|fixture-contact|Lantern Test/);
  });
  it("preserves independent public XML semantics through import and re-export", async () => {
    const imported = await convert(independentXml);
    const reexported = exportFdx(imported.source, { includeTitle: false });
    expect(await xmlFacts(reexported.xml)).toEqual(await xmlFacts(independentXml));
    const ownImport = await convert(exportFdx(source).xml);
    expect(visible(ownImport.source)).toEqual(visible(source));
    expect(ownImport.report.join(" ")).toMatch(/title-page/);
    expect(ownImport.source).not.toMatch(/PRIVATE_|fixture-contact|Lantern Test/);
  });
});
